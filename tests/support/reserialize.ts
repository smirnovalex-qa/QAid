/**
 * Тест-хелпер: воспроизводит семантику `chrome.scripting.executeScript({ world:
 * 'MAIN', func })`. Chrome сериализует переданную функцию как `func.toString()` и
 * исполняет её в контексте страницы — БЕЗ замыкания модуля, из которого она пришла.
 *
 * Реконструкция через `new Function` повторяет это один-в-один: любая ссылка на
 * биндинг уровня модуля (константа, хелпер, импорт-значение) становится свободным
 * идентификатором и падает `ReferenceError` при вызове — ровно как в реальной
 * MAIN-world странице. Поэтому прогон injected-функции ЧЕРЕЗ `reserialize` — это
 * контракт самодостаточности (ARCHITECTURE §7, ADR-0028): юнит-тест, дергающий
 * функцию напрямую в области модуля, эту утечку НЕ ловит.
 *
 * Живёт вне `src/**` намеренно: не входит в coverage-include и не подхватывается
 * как тестовый файл (vitest include — только `src/**`).
 */
export function reserialize<F extends (...args: never[]) => unknown>(fn: F): F {
  const src = fn.toString();
  // Оборачиваем в скобки: и `function name(){}`, и `(a) => {}` дают
  // корректное функциональное ВЫРАЖЕНИЕ (иначе `function`-декларация — не значение).
  return new Function(`return (${src});`)() as F;
}
